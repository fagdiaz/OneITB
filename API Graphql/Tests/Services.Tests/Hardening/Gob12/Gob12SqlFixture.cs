// These fixtures use the SQL Server provider. Missing opt-in/configuration fails explicitly.
public sealed class Gob12SqlFixture : IAsyncLifetime
{
    private readonly string databaseName = "OneITB_GOB12_" + Guid.NewGuid().ToString("N");
    private string masterConnection = string.Empty;
    private string databaseConnection = string.Empty;
    private bool created;

    public Guid Sender => ServiceTestData.StudentUserId;
    public Guid Receiver => ServiceTestData.TeacherUserId;
    public Guid OtherReceiver => ServiceTestData.OtherStudentUserId;
    public Guid Admin => ServiceTestData.AdminUserId;
    public Guid SecondProfessor { get; } = Guid.NewGuid();
    public int SubjectId { get; private set; }
    public Guid SectionId { get; } = Guid.NewGuid();

    public async Task InitializeAsync()
    {
        if (Environment.GetEnvironmentVariable("ONEITB_RUN_GOB12_SQL") != "true")
            throw new InvalidOperationException("Set ONEITB_RUN_GOB12_SQL=true to run GOB12 SQL concurrency tests.");
        var configured = Environment.GetEnvironmentVariable("ONEITB_GOB12_SQL_ADMIN");
        if (string.IsNullOrWhiteSpace(configured))
            throw new InvalidOperationException("ONEITB_GOB12_SQL_ADMIN must identify the disposable SQL Server 2022 test instance.");

        var builder = new SqlConnectionStringBuilder(configured) { InitialCatalog = "master", Pooling = false };
        masterConnection = builder.ConnectionString;
        builder.InitialCatalog = databaseName;
        databaseConnection = builder.ConnectionString;
        try
        {
            await using var connection = new SqlConnection(masterConnection);
            await connection.OpenAsync();
            await using var command = connection.CreateCommand();
            command.CommandText = $"CREATE DATABASE [{databaseName}]";
            command.CommandTimeout = 30;
            await command.ExecuteNonQueryAsync();
            created = true;
            await using var context = Open();
            // Build the actual EF model, including SQL indexes, rowversion and FK constraints.
            // Migration-chain acceptance remains a separate gate.
            await context.Database.EnsureCreatedAsync();
            var career = new Career { Name = "GOB12 " + databaseName, Code = "G12", IsActive = true };
            var subject = new Subject { Name = "Concurrency", Code = "G12", Career = career, Year = 1, IsActive = true };
            context.Subjects.Add(subject);
            var users = new[] {
                ServiceTestData.CreateUser(Sender, "Sender", "Fixture", "Estudiante", true),
                ServiceTestData.CreateUser(Receiver, "First", "Professor", "Profesor", true),
                ServiceTestData.CreateUser(OtherReceiver, "Other", "Student", "Estudiante", true),
                ServiceTestData.CreateUser(Admin, "Fixture", "Admin", "Administrador", true),
                ServiceTestData.CreateUser(SecondProfessor, "Second", "Professor", "Profesor", true),
            };
            context.Accounts.AddRange(users.Select(user =>
                ServiceTestData.CreateAccount(user, user.Id.ToString("N") + "@gob12.test")));
            context.CourseSections.Add(new CourseSection {
                Id = SectionId, Subject = subject, Term = "2026-2C", Code = "G12",
            });
            context.SectionEnrollments.Add(new SectionEnrollment { SectionId = SectionId, StudentId = Sender });
            context.SectionInstructors.AddRange(
                new SectionInstructor { SectionId = SectionId, ProfessorId = Receiver },
                new SectionInstructor { SectionId = SectionId, ProfessorId = SecondProfessor });
            await context.SaveChangesAsync();
            SubjectId = subject.Id;
        }
        catch
        {
            await DisposeAsync();
            throw;
        }
    }

    public Gob12Context Open(params IInterceptor[] interceptors)
    {
        var builder = new DbContextOptionsBuilder<OneItbContext>()
            .UseSqlServer(databaseConnection, sql => sql.CommandTimeout(15));
        builder.AddInterceptors(interceptors);
        return new Gob12Context(builder.Options);
    }

    public async Task DisposeAsync()
    {
        if (!created) return;
        // databaseName is generated by this fixture. No name is accepted from configuration.
        if (!System.Text.RegularExpressions.Regex.IsMatch(databaseName, @"\AOneITB_GOB12_[a-f0-9]{32}\z"))
            throw new InvalidOperationException("Unexpected fixture database name.");
        await using var connection = new SqlConnection(masterConnection);
        await connection.OpenAsync();
        await using var command = connection.CreateCommand();
        command.CommandTimeout = 30;
        command.CommandText = $"ALTER DATABASE [{databaseName}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [{databaseName}]";
        await command.ExecuteNonQueryAsync();
        created = false;
    }
}

public sealed class Gob12Context : OneItbContext
{
    public Gob12Context(DbContextOptions<OneItbContext> options) : base(options) { }
    public Gob12PairGate? SaveGate { get; set; }

    public override async Task<int> SaveChangesAsync(CancellationToken cancellationToken = default)
    {
        if (SaveGate != null) await SaveGate.ArriveAsync(cancellationToken);
        return await base.SaveChangesAsync(cancellationToken);
    }
}

// One-shot rendezvous, bounded and reusable by retries after the first two arrivals.
public sealed class Gob12PairGate
{
    private readonly TaskCompletionSource ready = new(TaskCreationOptions.RunContinuationsAsynchronously);
    private int arrivals;
    public int Arrivals => Volatile.Read(ref arrivals);

    public async Task ArriveAsync(CancellationToken cancellationToken)
    {
        if (Interlocked.Increment(ref arrivals) == 2) ready.TrySetResult();
        await ready.Task.WaitAsync(TimeSpan.FromSeconds(10), cancellationToken);
    }
}

public sealed class Gob12TransactionGate : DbTransactionInterceptor
{
    private readonly Gob12PairGate gate = new();
    public ConcurrentBag<IsolationLevel> IsolationLevels { get; } = new();
    public int Arrivals => gate.Arrivals;

    public override async ValueTask<InterceptionResult<DbTransaction>> TransactionStartingAsync(
        DbConnection connection, TransactionStartingEventData eventData,
        InterceptionResult<DbTransaction> result, CancellationToken cancellationToken = default)
    {
        // Both service calls finished their pretransaction checks before either begins a transaction.
        // No SQL locks are held by this rendezvous.
        IsolationLevels.Add(eventData.IsolationLevel);
        await gate.ArriveAsync(cancellationToken);
        return result;
    }
}

public sealed record Gob12Outcome<T>(T? Value, Exception? Error) where T : class
{
    public static async Task<Gob12Outcome<T>> Capture(Func<Task<T>> action)
    {
        try { return new(await action(), null); }
        catch (Exception error) { return new(null, error); }
    }
}
